    fun findById(id: String): Product? = sampleProducts.firstOrNull { it.id == id }

    fun searchProducts(query: String): List<Product> {
        val trimmed = query.trim().lowercase()
        if (trimmed.isEmpty()) return sampleProducts
        return sampleProducts.filter { product ->
            product.banglaName.lowercase().contains(trimmed) ||
                    product.englishName.lowercase().contains(trimmed) ||
                    product.category.banglaName.lowercase().contains(trimmed) ||
                    product.category.englishName.lowercase().contains(trimmed) ||
                    product.tags.any { it.lowercase().contains(trimmed) }
        }
    }
